-- В прод-схеме (дамп) не оказалось двух таблиц, которые использует приложение.
-- Без них страница переписки по обращению (/app/feedback-chat/{id}) падала с 500,
-- а учёт участников чатов не работал.

create table if not exists feedback_chat (
    id bigint generated by default as identity primary key,
    feedback_id bigint,
    user_id varchar(255),
    user_name varchar(255),
    date_time timestamp,
    description text
);

create index if not exists idx_feedback_chat_feedback_id on feedback_chat (feedback_id);

alter table feedback_chat drop constraint if exists fk_feedback_chat_feedback;
alter table feedback_chat add constraint fk_feedback_chat_feedback
    foreign key (feedback_id) references feedback (id) on delete cascade;

create table if not exists chat_member (
    id bigint generated by default as identity primary key,
    user_id varchar(255),
    chat_id varchar(255),
    last_message timestamp
);

create index if not exists idx_chat_member_chat_id on chat_member (chat_id);
create index if not exists idx_chat_member_chat_user on chat_member (chat_id, user_id);
