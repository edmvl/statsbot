-- Вложения рекламных постов: не больше 3 файлов на пост.
-- Файлы лежат на диске в каталоге <file.upload-dir>/ads/<ads_id>/<stored_name>,
-- здесь хранятся только метаданные и имя файла для выдачи.

create table if not exists ads_file (
    id integer generated by default as identity primary key,
    ads_id integer not null,
    original_name varchar(255) not null,
    stored_name varchar(255) not null,
    content_type varchar(255),
    file_size bigint,
    created_at timestamp not null default now()
);

create index if not exists idx_ads_file_ads_id on ads_file (ads_id);

alter table ads_file drop constraint if exists fk_ads_file_ads;
alter table ads_file add constraint fk_ads_file_ads
    foreign key (ads_id) references ads (id) on delete cascade;
