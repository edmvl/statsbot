-- Жалобы: пользователь, на которого жалуются (может быть не указан).
alter table feedback add column if not exists target_user_id varchar(255);
alter table feedback add column if not exists target_user_name varchar(255);

-- Список заблокированных пользователей. Хранит связь с жалобой, по которой забанили.
create table if not exists banned_user (
    id bigint generated by default as identity primary key,
    user_id varchar(255) not null,
    chat_id varchar(255),
    user_name varchar(255),
    feedback_id bigint,
    banned_by varchar(255),
    banned_at timestamp not null default now()
);

create index if not exists idx_banned_user_user_id on banned_user (user_id);
create index if not exists idx_banned_user_feedback_id on banned_user (feedback_id);

alter table banned_user drop constraint if exists fk_banned_user_feedback;
alter table banned_user add constraint fk_banned_user_feedback
    foreign key (feedback_id) references feedback (id) on delete set null;
